const prefixes = ["ก", "ข", "ค", "ง"];

function goToRegister() {
    document.getElementById("start-screen").classList.add("hidden");
    document.getElementById("register-screen").classList.remove("hidden");
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

function startQuiz(event) {
    event.preventDefault();
    robloxName = document.getElementById("roblox-name").value;

    document.getElementById("register-screen").classList.add("hidden");
    document.getElementById("quiz-screen").classList.remove("hidden");
    document.getElementById("user-greeting").innerText = `ผู้สอบ: ${robloxName}`;

    renderQuiz();
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

function renderQuiz() {
    const container = document.getElementById("questions-container");
    container.innerHTML = "";
    let currentSection = "";

    questions.forEach((q) => {
        if (q.section !== currentSection) {
            currentSection = q.section;
            const sectionHeader = document.createElement("div");
            sectionHeader.className = "section-header";
            sectionHeader.innerText = currentSection;
            container.appendChild(sectionHeader);
        }

        const card = document.createElement("div");
        card.className = "question-card";

        let optionsHTML = "";
        q.options.forEach((opt, i) => {
            const prefix = prefixes[i];
            optionsHTML += `
                <label>
                    <input type="radio" name="q${q.id}" value="${prefix}" required>
                    <strong>${prefix}.</strong>&nbsp;${opt}
                </label>
            `;
        });

        card.innerHTML = `
            <div class="question-text">${q.id}. ${q.title}</div>
            <div class="options">${optionsHTML}</div>
        `;
        container.appendChild(card);
    });
}

function calculateScore() {
    let part1Correct = 0; // ภาคที่ 1 (20 ข้อ ข้อละ 5 คะแนน)
    let part2Correct = 0; // ภาคที่ 2 (10 ข้อ ข้อละ 10 คะแนน)
    let answered = 0;

    questions.forEach(q => {
        const selected = document.querySelector(`input[name="q${q.id}"]:checked`);
        if (selected) {
            answered++;
            if (selected.value === q.answer) {
                if (q.part === 1) {
                    part1Correct++;
                } else if (q.part === 2) {
                    part2Correct++;
                }
            }
        }
    });

    if (answered < questions.length) {
        if (!confirm(`ท่านยังทำข้อสอบไม่ครบ (ทำไป ${answered}/30 ข้อ) ต้องการส่งข้อสอบเลยหรือไม่?`)) {
            return;
        }
    }

    const part1Score = part1Correct * 5;  // เต็ม 100
    const part2Score = part2Correct * 10; // เต็ม 100
    const totalScore = part1Score + part2Score; // เต็ม 200
    const totalPercentage = ((totalScore / 200) * 100).toFixed(1);

    // ตรวจสอบเกณฑ์แยกภาค (ต้องได้ 70 คะแนนขึ้นไปต่อภาค)
    const part1Pass = part1Score >= 70;
    const part2Pass = part2Score >= 70;
    const isOverallPass = part1Pass && part2Pass;

    // สลับไปยังหน้าแสดงผลการประเมิน (Result Screen)
    document.getElementById("quiz-screen").classList.add("hidden");
    document.getElementById("result-screen").classList.remove("hidden");
    window.scrollTo({ top: 0, behavior: 'smooth' });

    // แสดงผลข้อมูลบุคคล
    document.getElementById("result-name").innerText = `ยศ-ชื่อ: ${robloxName}`;

    // แสดงผลสรุปภาพรวม
    const statusBadge = document.getElementById("status-badge");
    if (isOverallPass) {
        statusBadge.className = "part-status part-pass";
        statusBadge.style.fontSize = "16px";
        statusBadge.style.padding = "12px 20px";
        statusBadge.innerText = "🎉 ผ่านการคัดเลือก (ผ่านเกณฑ์ทั้ง 2 ภาค)";
    } else {
        statusBadge.className = "part-status part-fail";
        statusBadge.style.fontSize = "16px";
        statusBadge.style.padding = "12px 20px";
        statusBadge.innerText = "❌ ไม่ผ่านการคัดเลือก (ต้องผ่านเกณฑ์ 70 คะแนนทั้ง 2 ภาค)";
    }

    // แสดงผลคะแนนภาค 1 ในกล่อง
    document.getElementById("part1-score-text").innerText = `${part1Score} / 100`;
    const part1StatusText = document.getElementById("part1-status-text");
    if (part1Pass) {
        part1StatusText.className = "part-status part-pass";
        part1StatusText.innerText = `ผ่านเกณฑ์ (ถูก ${part1Correct}/20 ข้อ)`;
    } else {
        part1StatusText.className = "part-status part-fail";
        part1StatusText.innerText = `ไม่ผ่าน (ถูก ${part1Correct}/20 ข้อ)`;
    }

    // แสดงผลคะแนนภาค 2 ในกล่อง
    document.getElementById("part2-score-text").innerText = `${part2Score} / 100`;
    const part2StatusText = document.getElementById("part2-status-text");
    if (part2Pass) {
        part2StatusText.className = "part-status part-pass";
        part2StatusText.innerText = `ผ่านเกณฑ์ (ถูก ${part2Correct}/10 ข้อ)`;
    } else {
        part2StatusText.className = "part-status part-fail";
        part2StatusText.innerText = `ไม่ผ่าน (ถูก ${part2Correct}/10 ข้อ)`;
    }

    // แสดงคะแนนรวมในกล่องสรุปด้านล่าง
    document.getElementById("total-score-box").innerHTML = `${totalScore} <span style="font-size: 18px; color: #64748b;">/ 200</span>`;
    document.getElementById("total-percentage-box").innerText = `คิดเป็นคะแนนรวม: ${totalPercentage}%`;
}

function downloadResultImage() {
    const targetElement = document.getElementById("capture-area");

    html2canvas(targetElement, {
        scale: 2,
        useCORS: true,
        backgroundColor: "#0b1329"
    }).then(canvas => {
        const image = canvas.toDataURL("image/png");
        const link = document.createElement("a");
        link.href = image;
        link.download = `ผลการสอบ_ครูฝึกนายเรือ_${robloxName}.png`;
        link.click();
    });
}